pub fn hex_bytes(text: &str) -> Vec<u8> {
    let digits: String = text.split_whitespace().collect();
    assert_eq!(digits.len() % 2, 0, "odd number of hex digits");
    (0..digits.len() / 2)
        .map(|i| u8::from_str_radix(&digits[i * 2..i * 2 + 2], 16).expect("hex digit"))
        .collect()
}

pub fn wasm_target() -> Target {
    Target::from_triple("wasm32-wasi").expect("wasm32-wasi triple")
}

/// Write the fixture object into `dir` and link it, returning the module path.
pub fn link_object(dir: &Path, name: &str, hex: &str) -> PathBuf {
    let input = dir.join(format!("{name}.o"));
    fs::write(&input, hex_bytes(hex)).expect("write input object");
    let output = dir.join(format!("{name}.wasm"));
    Linker::link(&[input], LinkConfig::new(output.clone(), wasm_target()))
        .expect("the clang object links");
    output
}

/// Write several fixture objects into `dir` and link them together in the order
/// given, returning the module path. `name` names the output, not an object.
pub fn link_objects(dir: &Path, name: &str, objects: &[(&str, &str)]) -> PathBuf {
    let inputs: Vec<PathBuf> = objects
        .iter()
        .map(|(object_name, hex)| {
            let input = dir.join(format!("{object_name}.o"));
            fs::write(&input, hex_bytes(hex)).expect("write input object");
            input
        })
        .collect();
    let output = dir.join(format!("{name}.wasm"));
    let config = LinkConfig::new(output.clone(), wasm_target());
    Linker::link(&inputs, config).unwrap_or_else(|error| panic!("link {name}: {error}"));
    output
}
